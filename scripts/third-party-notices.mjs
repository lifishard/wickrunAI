/*
 * Writes the license files that are generated from other files:
 *
 * - THIRD_PARTY_LICENSES.txt: the name, version, license and license text of every
 *   production dependency that ships inside the packaged app (from package-lock.json and
 *   the installed packages). wickrunAI itself is proprietary; these components keep their
 *   own licenses, and most of them require their notice to travel with the app.
 * - build/license.txt: the Windows installer's "I Agree" page, which is LICENSE as UTF-8
 *   with a byte-order mark and CRLF line ends, so NSIS shows the Chinese text correctly.
 *
 *   node scripts/third-party-notices.mjs          regenerate the files (npm run licenses)
 *   node scripts/third-party-notices.mjs --check  fail when a file is out of date
 *
 * Platform-specific binaries (lockfile entries with `os`/`cpu`) are listed without their
 * text, because only one of them is installed on any machine; the output is therefore
 * identical on Windows, macOS and Linux.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUTPUT = 'THIRD_PARTY_LICENSES.txt';
export const INSTALLER_LICENSE = 'build/license.txt';
const BOM = '\ufeff';
const LICENSE_FILE = /^(licen[sc]e|copying|notice)([.-].*)?$/i;
const normalize = text => text.replace(/\r\n?/g, '\n').replace(/[ \t]+$/gm, '').trimEnd();

export function collectPackages(lock, root = ROOT) {
  const seen = new Map();
  for (const [where, entry] of Object.entries(lock.packages || {})) {
    if (!where || entry.dev || entry.link) continue;
    const name = entry.name || where.slice(where.lastIndexOf('node_modules/') + 'node_modules/'.length);
    const key = `${name}@${entry.version}`;
    if (seen.has(key)) continue;
    const platform = Boolean(entry.os || entry.cpu);
    let texts = [];
    if (!platform) {
      const dir = path.join(root, where);
      const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter(f => LICENSE_FILE.test(f) && fs.statSync(path.join(dir, f)).isFile()).sort() : [];
      texts = files.map(f => ({ file: f, text: normalize(fs.readFileSync(path.join(dir, f), 'utf8')) }));
    }
    seen.set(key, { name, version: entry.version, license: entry.license || 'UNKNOWN', platform, texts });
  }
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
}

export function render(packages) {
  const lines = [
    'wickrunAI (灯芯AI) — third-party software notices',
    '',
    'wickrunAI is proprietary software (see LICENSE). It includes the open-source',
    'components listed below. Each component is licensed to you under its own license,',
    'reproduced here; nothing in the wickrunAI license limits your rights under them.',
    'Where a component offers a choice of licenses, wickrunAI uses it under the',
    'permissive option (DOMPurify: Apache-2.0; JSZip: MIT).',
    '',
    'The Electron runtime ships its own notices next to the application executable',
    '(LICENSE.electron.txt and LICENSES.chromium.html).',
    '',
    'This file is generated by scripts/third-party-notices.mjs from package-lock.json.',
    '',
  ];
  const regular = packages.filter(p => !p.platform), platform = packages.filter(p => p.platform);
  lines.push(`Components (${regular.length}):`, '');
  for (const p of regular) lines.push(`  ${p.name} ${p.version} — ${p.license}`);
  if (platform.length) {
    lines.push('', 'Platform-specific binaries (only the one matching your system is installed):', '');
    for (const p of platform) lines.push(`  ${p.name} ${p.version} — ${p.license}`);
  }
  for (const p of regular) {
    lines.push('', '='.repeat(78), `${p.name} ${p.version}`, `License: ${p.license}`, '='.repeat(78), '');
    if (!p.texts.length) lines.push(`The package does not include a separate license file; it is distributed under ${p.license} according to its package metadata.`);
    for (const [i, t] of p.texts.entries()) {
      if (p.texts.length > 1) lines.push(`--- ${t.file} ---`, '');
      lines.push(t.text);
      if (i < p.texts.length - 1) lines.push('');
    }
  }
  return lines.join('\n') + '\n';
}

export function build(root = ROOT) {
  const lock = JSON.parse(fs.readFileSync(path.join(root, 'package-lock.json'), 'utf8'));
  return render(collectPackages(lock, root));
}

/** The installer's license page: LICENSE, with a pointer to the Chinese summary at its end. */
export function installerLicense(root = ROOT) {
  const license = normalize(fs.readFileSync(path.join(root, 'LICENSE'), 'utf8'));
  const text = `请阅读以下许可，中文说明在文末。点「我接受」即表示同意。\nPlease read the license below. Click "I Agree" to accept it.\n\n${license}\n`;
  return BOM + text.replace(/\n/g, '\r\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const outputs = [[OUTPUT, build()], [INSTALLER_LICENSE, installerLicense()]];
  // Git may change line ends on checkout (core.autocrlf on Windows), so compare text only.
  const same = (a, b) => normalize(a.replace(BOM, '')) === normalize(b.replace(BOM, ''));
  if (process.argv.includes('--check')) {
    const stale = outputs.filter(([name, next]) => { const file = path.join(ROOT, name); return !fs.existsSync(file) || !same(fs.readFileSync(file, 'utf8'), next); });
    if (stale.length) {
      console.error(`${stale.map(([name]) => name).join(', ')} out of date. Run: npm run licenses`);
      process.exit(1);
    }
    console.log('License files are up to date.');
  } else {
    for (const [name, next] of outputs) { fs.writeFileSync(path.join(ROOT, name), next); console.log(`Wrote ${name}.`); }
  }
}
